import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { defaultCabinet } from '../js/cabinet-math.js';
import { sharedStockChoices, splitStockAppearance } from '../js/material-presets.js';
const source = readFileSync(new URL('../js/main.js', import.meta.url), 'utf8');
const start = source.indexOf("let nestingSettingsTab = 'stock';");
const end = source.indexOf('function bindNestingViewEvents', start);
const config = defaultCabinet();
const context = vm.createContext({ currentConfig: config, currentProject: { cabinets: [{ config }] }, sharedStockChoices, splitStockAppearance, dimension: n => `${n} mm`, escapeHtml: s => String(s) });
vm.runInContext(source.slice(start, end), context);
let html = vm.runInContext('buildNestingControls(currentConfig)', context);
assert.match(html, /id="nesting-stock-panel"[^>]*>/);
assert.match(html, /id="nesting-sheet-panel"[^>]* hidden/);
assert.match(html, /data-stock-type="carcass" open/);
assert.match(html, /<summary>.*?<small>.*?18 mm<\/small>/s);
assert.equal((html.match(/<details /g) || []).length, 5);
assert.equal((html.match(/<\/details>/g) || []).length, 5);
vm.runInContext("nestingSettingsTab = 'sheet'; openStockType = 'rear'", context);
html = vm.runInContext('buildNestingControls(currentConfig)', context);
assert.match(html, /id="nesting-stock-panel"[^>]* hidden/);
assert.doesNotMatch(html.match(/id="nesting-sheet-panel"[^>]*>/)[0], /hidden/);
assert.match(html, /data-stock-type="rear" open/);
assert.doesNotMatch(html, /data-stock-type="carcass" open/);
console.log('PASS: stock/sheet tab markup, five stock rows, summaries and retained open selection');
