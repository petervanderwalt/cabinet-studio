// Mount from the generated bores, so moved/mirrored handles keep their drilling.
export function loadLocalBlumPreview(data, file) {
  const [expectedHash, parts] = new Map([
    ['clip-top', ['ff0556711165fe0511f2b8925923f0bdbf28e45a7a783684f15cb8bbf371b9d9', ['71B3550','71B3550-cup','71B3550-arm','173H7100']]],
    ['clip-top-inset', ['a469c12f8aa023b31487ee1cf447ed8d1b572c1b2ee4b9595fa43ab7edc2c87b', ['71B3750','71B3750-cup','71B3750-arm','173H7100-inset']]],
    ['movento-lock-right', ['90d7a46237f0fff4ef297e935b90f7352e6d1a1ceb3f12a506f260263dc04d5c', ['T51.7601R']]],
    ['movento-lock-left', ['275a727f96fd0f318ea1dd45757160ce6672264070e8947f8580b51b62a7d8ca', ['T51.7601L']]],
  ]).get(file) ?? [];
  if (!expectedHash || data?.sourceSha256 !== expectedHash) {
    throw new Error(`Wrong Blum CAD source for ${file}.`);
  }
  const models = parts.map(partNumber => {
    const positions = data.models?.[partNumber];
    if (!Array.isArray(positions) || !positions.length || positions.length % 9 ||
        positions.length > 600000 || !positions.every(v => Number.isFinite(v) && Math.abs(v) < 100)) {
      throw new Error(`Invalid preview geometry for Blum ${partNumber}.`);
    }
    return [`blum-${partNumber.toLowerCase()}`, {manufacturer:'Blum',partNumber,positions,
      previewColor:partNumber.startsWith('T51.') ? 0xe76b22 : undefined}];
  });
  Object.assign(HARDWARE_MODELS,Object.fromEntries(models));
}

export function handleModelPlacement(panel, preset) {
  if (!preset?.model || !['door', 'drawer'].includes(panel.type)) return [];
  const model = HARDWARE_MODELS[preset.model];
  const holes = (panel.holes || []).filter(h => h.purpose === 'handle');
  if (!model || holes.length !== model.mountingCentres.length) return [];
  if (holes.length===1) {
    const [hole]=holes;
    if (!Number.isFinite(hole.x) || !Number.isFinite(hole.y)) return [];
    const [x,y]=model.mountingCentres[0];
    if (hole.x+model.bounds[0][0]-x<0 || hole.x+model.bounds[0][1]-x>panel.cutWidth
      || hole.y+model.bounds[1][0]-y<0 || hole.y+model.bounds[1][1]-y>panel.cutHeight) return [];
    return [{model:preset.model,x:hole.x-panel.cutWidth/2-x,y:hole.y-panel.cutHeight/2-y,z:-panel.sizeZ/2,rotation:0}];
  }
  const a = holes[0], b = holes.at(-1);
  const dx = b.x - a.x, dy = b.y - a.y;
  const spacing = model.mountingCentres.at(-1)[0] - model.mountingCentres[0][0];
  if (![a.x, a.y, b.x, b.y].every(Number.isFinite) || Math.abs(Math.hypot(dx, dy) - spacing) > 0.001) return [];
  const x = (a.x + b.x) / 2, y = (a.y + b.y) / 2;
  if (holes.length === 3 && !(Math.hypot(holes[1].x - x, holes[1].y - y) < 0.001)) return [];
  if (preset.keepWithinFront || model === salvia || model === salvia128 || model === salvia160 || model === salvia192 || model === salvia224 || model === salvia256) {
    const cos = dx / spacing, sin = dy / spacing;
    for (const u of model.bounds[0]) for (const v of model.bounds[1]) {
      const px = x + u * cos - v * sin, py = y + u * sin + v * cos;
      if (px < -1e-6 || px > panel.cutWidth + 1e-6 || py < -1e-6 || py > panel.cutHeight + 1e-6) return [];
    }
  }
  return [{ model: preset.model, x: x - panel.cutWidth / 2,
    y: y - panel.cutHeight / 2, z: -panel.sizeZ / 2, rotation: Math.atan2(dy, dx) }];
}
